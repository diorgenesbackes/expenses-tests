import { expect, test, type Page } from '@playwright/test'
import { newEmail, password, register } from '../support/http.js'
async function enter(page: Page, email: string, secret = password) {
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(secret)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
}
test('UI-01 login responsivo e acessível por teclado', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Entre na sua conta' })).toBeVisible()
  await page.screenshot({ path: `reports/${process.env.LAB_RUN_ID}/login-desktop.png` })
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByLabel('E-mail', { exact: true })).toBeFocused()
  await page.setViewportSize({ width: 375, height: 812 })
  await expect(page.getByRole('link', { name: 'Criar conta' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `reports/${process.env.LAB_RUN_ID}/login-mobile.png` })
})
test('UI-02 cadastro, login, recarga e logout pela interface', async ({ page, context }) => {
  const email = newEmail()
  await page.goto('/cadastro')
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Criar minha conta' }).click()
  await expect(page.getByRole('status')).toContainText('Conta criada!')
  await expect(page.getByRole('button', { name: 'Sair da conta' })).toHaveCount(0)
  await enter(page, email)
  await expect(page.getByText(email, { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText(email, { exact: true })).toBeVisible()
  expect(await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))).toEqual({ local: {}, session: {} })
  // Force access expiry by removing only its cookie; current must renew from HttpOnly refresh.
  await context.clearCookies({ name: 'cc_at' })
  await page.reload()
  await expect(page.getByText(email, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await expect(page.getByRole('heading', { name: 'Entre na sua conta' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Entre na sua conta' })).toBeVisible()
})
test('UI-03 tentativas restantes e bloqueio não impedem outra conta', async ({ page, request }) => {
  const user = await register(request)
  const other = await register(request)
  await page.goto('/login')
  for (let attempt = 1; attempt <= 10; attempt++) {
    await enter(page, user.email, 'WrongPassword123!')
    const message = page.getByRole('alert')
    if (attempt === 10) await expect(message).toContainText('temporariamente bloqueado')
    else if (attempt >= 7) await expect(message).toContainText(`Restam ${10 - attempt} tentativas`)
    else await expect(message).toContainText('E-mail ou senha incorretos')
  }
  await enter(page, other.email)
  await expect(page.getByText(other.email, { exact: true })).toBeVisible()
})
test('UI-04 lembra somente email por opção e remove ao desmarcar', async ({ page, request }) => {
  const user = await register(request)
  await page.goto('/login')
  await page.getByRole('checkbox', { name: 'Lembrar meu e-mail' }).check()
  await enter(page, user.email)
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await page.reload()
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue(user.email)
  expect(await page.evaluate(() => ({ ...localStorage }))).toEqual({ 'expenses.remembered-email': user.email })
  await page.getByRole('checkbox').uncheck()
  expect(await page.evaluate(() => localStorage.length)).toBe(0)
})
test('UI-05 logout limpa identidade nas outras abas imediatamente', async ({ page, context, request }) => {
  const user = await register(request)
  await page.goto('/login'); await enter(page, user.email)
  await expect(page.getByText(user.email, { exact: true })).toBeVisible()
  const second = await context.newPage()
  await second.goto('/')
  await expect(second.getByText(user.email, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await expect(second.getByRole('heading', { name: 'Entre na sua conta' })).toBeVisible()
  await expect(second.getByText(user.email, { exact: true })).toHaveCount(0)
})
